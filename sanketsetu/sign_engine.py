def _find_hands(detector, img):
    """cvzone changed its return type between versions: (hands, img) vs hands."""
    res = detector.findHands(img, draw=False, flipType=True)
    if isinstance(res, tuple):
        res = res[0]
    return res or []


class SignEngine:
    """One instance = one user's running sentence. The Keras model is shared."""

    def __init__(self, model, model_lock, detector_factory):
        self.model = model
        self._lock = model_lock
        self.hd = detector_factory()   # hand finder on the full frame
        self.hd2 = detector_factory()  # hand finder on the cropped hand
        self.ct = {"blank": 0}
        self.blank_flag = 0
        self.space_flag = False
        self.next_flag = True
        self.prev_char = ""
        self.count = -1
        self.ten_prev_char = [" "] * 10
        self.str = " "
        self.word = " "
        self.current_symbol = " "
        self.pts = None
        self.suggestions = []

    # ---- helpers the copied code expects -------------------------------------------------
    def distance(self, x, y):
        return math.sqrt(((x[0] - y[0]) ** 2) + ((x[1] - y[1]) ** 2))

    def _model_predict(self, white):
        with self._lock:  # Keras predict is not safe to call from several request threads at once
            return self.model.predict(white, verbose=0)

    # ---- public API ----------------------------------------------------------------------
    def clear(self):
        self.str = " "
        self.word = " "
        self.prev_char = ""
        self.count = -1
        self.ten_prev_char = [" "] * 10
        self.current_symbol = " "
        self.suggestions = []

    def backspace(self):
        self.str = self.str[:-1] if len(self.str) > 1 else " "
        self._refresh_suggestions()

    def add_current_letter(self):
        """Manual fallback for the 'next' gesture: append the letter currently being shown."""
        sym = self._letter()
        if sym and len(sym) == 1 and sym.isalpha():
            self.str += sym
            self._refresh_suggestions()

    def add_space(self):
        if not self.str.endswith(" "):
            self.str += " "
        self._refresh_suggestions()

    def apply_suggestion(self, index):
        """Replace the word being spelled with suggestion #index (mirrors action1..4 in the desktop app)."""
        if not (0 <= index < len(self.suggestions)):
            return
        idx_space = self.str.rfind(" ")
        self.str = self.str[: idx_space + 1] + self.suggestions[index].upper()
        self._refresh_suggestions()

    def process_frame(self, frame_bgr):
        """frame_bgr: un-mirrored BGR image from the camera. Returns a JSON-able dict."""
        frame = cv2.flip(frame_bgr, 1)  # final_pred.py mirrors the camera before detection
        out = {"hand": False, "letter": None, "skeleton": None}
        hands = _find_hands(self.hd, frame)
        if not hands:
            out.update(self._state())
            return out

        x, y, w, h = hands[0]["bbox"]
        H, W = frame.shape[:2]
        y0, y1 = max(0, y - OFFSET), min(H, y + h + OFFSET)
        x0, x1 = max(0, x - OFFSET), min(W, x + w + OFFSET)
        crop = frame[y0:y1, x0:x1]
        if crop.size == 0:
            out.update(self._state())
            return out

        handz = _find_hands(self.hd2, crop)
        if not handz:
            out.update(self._state())
            return out

        self.pts = handz[0]["lmList"]
        white = self._draw_skeleton(w, h)
        try:
            self._classify(white.copy())
        except Exception:
            # The desktop app wrapped each frame in try/except and carried on; a handful of rule paths can leave a
            # numeric group id (not a letter) in the sign history and fail when it is appended to the text.
            # Treat that frame as "nothing recognised" rather than erroring the request.
            log.debug("classifier skipped a frame", exc_info=True)
        self._refresh_suggestions()

        ok, jpg = cv2.imencode(".jpg", white, [cv2.IMWRITE_JPEG_QUALITY, 80])
        out["hand"] = True
        out["skeleton"] = "data:image/jpeg;base64," + base64.b64encode(jpg).decode() if ok else None
        out.update(self._state())
        out["letter"] = self._letter()
        return out

    # ---- internals -----------------------------------------------------------------------
    def _letter(self):
        s = self.current_symbol
        return s if isinstance(s, str) else None  # unresolved numeric groups are not letters

    def _state(self):
        return {"sentence": self.str.strip("\n"), "suggestions": self.suggestions}

    def _refresh_suggestions(self):
        self.suggestions = []
        if _DICT is None or not self.str.strip():
            return
        word = self.str[self.str.rfind(" ") + 1:]
        self.word = word
        if word.strip():
            try:
                self.suggestions = [s.upper() for s in _DICT.suggest(word)[:4]]
            except Exception:
                self.suggestions = []

    def _draw_skeleton(self, w, h):
        """Draws the 21 hand landmarks on a white 400x400 canvas - the exact input the CNN was trained on."""
        pts = self.pts
        white = np.ones((400, 400, 3), np.uint8) * 255
        os_ = ((400 - w) // 2) - 15
        os1 = ((400 - h) // 2) - 15
        green = (0, 255, 0)

        def P(i):
            return (int(pts[i][0] + os_), int(pts[i][1] + os1))

        for start, stop in ((0, 4), (5, 8), (9, 12), (13, 16), (17, 20)):
            for t in range(start, stop):
                cv2.line(white, P(t), P(t + 1), green, 3)
        for a, b in ((5, 9), (9, 13), (13, 17), (0, 5), (0, 17)):
            cv2.line(white, P(a), P(b), green, 3)
        for i in range(21):
            cv2.circle(white, P(i), 2, (0, 0, 255), 1)
        return white

