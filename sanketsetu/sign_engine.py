"""
sign_engine.py - browser-friendly wrapper around the Sign -> Text logic from
Sign-Language-To-Text-and-Speech-Conversion (final_pred.py).

What is NOT changed: the CNN model file and the whole landmark-rule classifier
(`_classify` below is final_pred.py's `Application.predict`, copied line for line;
only `self.model.predict(...)` was routed through `_model_predict` and its debug
`print(...)` calls were silenced).

What IS different from the desktop app:
  * no Tkinter / OpenCV window / pyttsx3 - frames come in as JPEG bytes from the browser
  * speaking is done in the browser (Web Speech API), not on the server
  * word suggestions use `pyenchant` only if it is installed (optional)
  * hand-crop slicing is clamped to the frame so a hand at the edge doesn't crash
"""
